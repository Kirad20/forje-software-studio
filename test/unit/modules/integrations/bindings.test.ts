import { beforeEach, expect, it, vi } from "vitest";
const db = vi.hoisted(() => ({ q: vi.fn(async (..._args: any[]): Promise<any[]> => []), one: vi.fn(async (..._args: any[]): Promise<any> => undefined) }));
vi.mock("../../../../server/shared/database/index.js", () => db);
import { bindMemorySecretDetector, addMemory } from "../../../../server/modules/memory/memory.js";
import { bindSecurityPorts, runQuickScan } from "../../../../server/modules/project-observability/security.js";
import { bindProblemPorts, recheckBuild, watchProblems } from "../../../../server/modules/project-observability/problems.js";
import { projectEvents } from "../../../../server/modules/project-observability/events.js";
import { bindGithubProjectPorts, syncProject, watchLinked } from "../../../../server/modules/integrations/github.js";
import { githubGateway, githubRepository } from "../../../../server/modules/integrations/infrastructure/github.js";
const deferred = <T>() => { let resolve!: (value: T) => void; const promise = new Promise<T>((r) => { resolve = r; }); return { resolve, promise }; };
beforeEach(() => { db.q.mockReset().mockResolvedValue([]); db.one.mockReset().mockResolvedValue(undefined); });
it("memory cleanup is conditional on its binding token, even when the same detector is rebound", async () => {
  const detector = () => "blocked";
  const releaseOld = bindMemorySecretDetector(detector);
  const release = bindMemorySecretDetector(detector);
  await releaseOld();
  await expect(addMemory("p", "a", { scope: "project", kind: "business", text: "fact", source: "owner" })).rejects.toThrow("blocked");
  await release(); await release();
  await expect(addMemory("p", "a", { scope: "project", kind: "business", text: "fact", source: "owner" })).rejects.toThrow("not bound");
});
it("security cleanup drains scans before releasing their captured ports", async () => {
  const read = deferred<Record<string, string>>();
  const quickScan = vi.fn(() => []);
  const release = bindSecurityPorts({ readAllFiles: () => read.promise, quickScan });
  const work = runQuickScan("p");
  let done = false;
  const cleanup = release().then(() => { done = true; });
  await new Promise((r) => setTimeout(r, 0));
  expect(done).toBe(false);
  read.resolve({ file: "code" });
  await work; await cleanup;
  expect(quickScan).toHaveBeenCalledWith({ file: "code" });
  await expect(runQuickScan("p")).rejects.toThrow("not bound");
  const releaseOld = bindSecurityPorts({ readAllFiles: async () => ({}), quickScan: () => [] });
  const releaseNew = bindSecurityPorts({ readAllFiles: async () => ({}), quickScan: () => [] });
  await releaseOld();
  await expect(runQuickScan("p")).resolves.toEqual([]);
  await releaseNew();
});
it("problem cleanup detaches listeners and drains pending build checks before unbinding", async () => {
  const check = deferred<any[]>();
  const ports = { readAllFiles: async () => ({}), checkProject: () => check.promise, formatProblem: () => "" };
  const stale = bindProblemPorts(ports), release = bindProblemPorts(ports);
  await stale();
  watchProblems("binding-project");
  const work = recheckBuild("binding-project");
  await Promise.resolve();
  const cleanup = release();
  expect(projectEvents.listenerCount("binding-project")).toBe(0);
  check.resolve([]);
  await work; await cleanup;
  await expect(recheckBuild("binding-project")).rejects.toThrow("not bound");
});
it("GitHub cleanup detaches listeners and drains queued sync before releasing bound ports", async () => {
  const local = deferred<Record<string, string>>(), unsubscribe = vi.fn();
  const ports = { readAllFiles: () => local.promise, writeFile: vi.fn(), deleteFile: vi.fn(), assertValidPath: vi.fn(), recheckBuild: async () => [], emitProject: vi.fn(), subscribe: () => unsubscribe };
  const stale = bindGithubProjectPorts(ports), release = bindGithubProjectPorts(ports);
  await stale();
  watchLinked("p");
  db.one.mockResolvedValueOnce({ project_id: "p", account_id: "a", owner: "o", repo: "r", branch: "main", last_sha: "head", last_tree: "tree", synced: {}, status: "ok" }).mockResolvedValueOnce({ token_enc: "token", login: "user" });
  const token = vi.spyOn(githubRepository, "token").mockResolvedValue({ token: "token", login: "user" });
  const request = vi.spyOn(githubGateway, "request").mockImplementation(async (_t, _m, path): Promise<any> => path.includes("/ref/") ? { object: { sha: "head" } } : { tree: { sha: "tree" } });
  const work = syncProject("p").catch(() => {});
  await vi.waitFor(() => expect(request).toHaveBeenCalledTimes(2));
  let done = false;
  const cleanup = release().then(() => { done = true; });
  expect(unsubscribe).toHaveBeenCalledOnce();
  await new Promise((r) => setTimeout(r, 0)); expect(done).toBe(false);
  local.resolve({});
  await work; await cleanup;
  expect(() => watchLinked("new")).toThrow("not bound");
  token.mockRestore(); request.mockRestore();
});
