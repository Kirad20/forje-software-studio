import { readFileSync } from "node:fs";
import path from "node:path";
import { ROOT_DIR } from "../../../shared/config.js";
import { dataRole, layoutMigrations, layoutOf, readLayout, safeLayout, under, type ProjectComponent, type ProjectLayout } from "../../../../contracts/projectLayout.js";
import type { FileMap } from "../domain/publication.js";
import { endpointRoutes, jobFiles, pageRoutes, readJobSettings } from "../domain/routes.js";
import { BuildError, buildClient, checkProject, compileServerModule } from "./bundler.js";
import { readDeps } from "./deps.js";

/**
 * "Exportar para producción": the project as a stack that runs without Forja, from its
 * forja.json components. One container per api/worker (and the app's own endpoints), a
 * gateway that serves every frontend at its mount and routes /_api, Postgres with one schema
 * and role per component that owns a database, and a migration step.
 *
 * Code is compiled with Forja's own bundler, so the export runs exactly what the preview runs.
 * Forja's platform services (sign-in, storage, email, AI, realtime, payments) are not part of
 * the export: the runtime answers 501 for them, and the README says so.
 */
export interface StandaloneExportInput {
  name: string;
  slug: string;
  files: FileMap;
  /** Names of the project's secrets (never their values): they become environment variables. */
  secrets: string[];
}

export type ExportTree = Record<string, string | Uint8Array>;

const STANDALONE_DIR = path.join(ROOT_DIR, "server", "modules", "app-runtime", "infrastructure", "standalone");
const RUNTIME_PACKAGES = ["pg", "croner"];

const installedVersion = (name: string) => {
  try {
    return JSON.parse(readFileSync(path.join(ROOT_DIR, "node_modules", name, "package.json"), "utf8")).version as string;
  } catch {
    return "latest";
  }
};

const envName = (schema: string) => `DB_PASSWORD_${schema.toUpperCase()}`;
const bundleName = (file: string) => `${file.replace(/\.ts$/, "").replace(/[^A-Za-z0-9]+/g, "_")}.mjs`;
const staticBytes = (content: string): string | Uint8Array => (content.startsWith("base64:") ? new Uint8Array(Buffer.from(content.slice(7), "base64")) : content);
const escapeHtml = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);

interface ServiceUnit {
  name: string;
  component: ProjectComponent;
  endpoints: { method: string; route: string; file: string }[];
  jobs: { name: string; file: string }[];
}

/** Bare package imports left in a compiled server bundle (they are installed in its image). */
function bareImports(code: string): string[] {
  const names = new Set<string>();
  for (const m of code.matchAll(/(?:from\s*|import\s*\(\s*|import\s+)["']([^"'./][^"']*)["']/g)) {
    const spec = m[1]!;
    if (spec.startsWith("node:")) continue;
    const name = spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0]!;
    if (!name.startsWith("@forja/")) names.add(name);
  }
  return [...names];
}

function services(files: FileMap, layout: ProjectLayout): ServiceUnit[] {
  const endpoints = endpointRoutes(files, layout), jobs = jobFiles(files, layout);
  const units: ServiceUnit[] = [];
  for (const component of layout.components) {
    if (component.kind !== "app" && component.kind !== "api" && component.kind !== "worker") continue;
    const name = component.name;
    const own = (c?: string) => (c ?? "app") === name;
    const unit: ServiceUnit = {
      name, component,
      endpoints: endpoints.filter((e) => own(e.component)).map((e) => ({ method: e.method, route: e.route, file: e.file })),
      jobs: jobs.filter((j) => own(j.component)).map((j) => ({ name: j.name, file: j.file })),
    };
    if (unit.endpoints.length || unit.jobs.length) units.push(unit);
  }
  return units;
}

function nginxConf(units: ServiceUnit[], webMounts: string[]): string {
  const api = units.filter((u) => u.endpoints.length);
  const lines = [
    "# Generated by Forja: every frontend at its mount, /_api routed to its service.",
    "server {",
    "  listen 80;",
    "  client_max_body_size 10m;",
    "  root /usr/share/nginx/html;",
    "  location /_baas/ {",
    "    default_type application/json;",
    `    return 501 '{"error":"Los servicios de la plataforma Forja (inicio de sesión, archivos, correo, IA, tiempo real, pagos) no forman parte de la exportación."}';`,
    "  }",
    "  location /_forja/ { try_files $uri =404; }",
  ];
  for (const unit of api.filter((u) => u.component.kind === "api")) {
    lines.push(`  location /_api/${unit.component.route}/ { proxy_pass http://${unit.name}:3000; proxy_set_header Host $host; proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for; }`);
  }
  const app = api.find((u) => u.component.kind === "app");
  lines.push(app
    ? "  location /_api/ { proxy_pass http://app:3000; proxy_set_header Host $host; proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for; }"
    : `  location /_api/ { default_type application/json; return 404 '{"error":"No existe ese endpoint"}'; }`);
  for (const mount of webMounts.filter((m) => m !== "/").sort((a, b) => b.length - a.length)) {
    lines.push(`  location = ${mount} { try_files ${mount}/index.html =404; }`);
    lines.push(`  location ${mount}/ { try_files $uri ${mount}/index.html; }`);
  }
  lines.push(webMounts.includes("/") ? "  location / { try_files $uri /index.html; }" : `  location / { default_type text/plain; return 404 'Not found'; }`);
  lines.push("}");
  return lines.join("\n") + "\n";
}

function compose(slug: string, units: ServiceUnit[], schemas: string[], secrets: string[], hasWeb: boolean): string {
  const db = (user: string, passwordVar: string) => `postgres://${user}:\${${passwordVar}}@db:5432/app`;
  const out = [
    `# Generated by Forja for "${slug}". Copy .env.example to .env, set the passwords and run: docker compose up --build`,
    "services:",
    "  db:",
    "    image: postgres:17-alpine",
    "    environment:",
    "      POSTGRES_DB: app",
    "      POSTGRES_PASSWORD: ${POSTGRES_PASSWORD}",
    "    volumes:",
    "      - db-data:/var/lib/postgresql/data",
    "    healthcheck:",
    "      test: [\"CMD-SHELL\", \"pg_isready -U postgres -d app\"]",
    "      interval: 5s",
    "      retries: 20",
    "  migrate:",
    "    build: ./migrate",
    "    environment:",
    `      DATABASE_URL: ${db("postgres", "POSTGRES_PASSWORD")}`,
    "      APP_DB_PASSWORD: ${APP_DB_PASSWORD}",
    ...schemas.map((s) => `      ${envName(s)}: \${${envName(s)}}`),
    "    depends_on:",
    "      db:",
    "        condition: service_healthy",
    "    restart: \"no\"",
  ];
  for (const unit of units) {
    const schema = unit.component.database;
    out.push(
      `  ${unit.name}:`,
      `    build: ./services/${unit.name}`,
      "    environment:",
      `      DATABASE_URL: ${schema ? db(dataRole(schema), envName(schema)) : db("forja_app", "APP_DB_PASSWORD")}`,
      ...secrets.map((name) => `      ${name}: \${${name}:-}`),
      "    depends_on:",
      "      migrate:",
      "        condition: service_completed_successfully",
      "    restart: unless-stopped",
    );
    if (unit.component.replicas && unit.component.replicas > 1) out.push("    deploy:", `      replicas: ${unit.component.replicas}`);
  }
  if (hasWeb || units.some((u) => u.endpoints.length)) {
    out.push("  gateway:", "    build: ./gateway", "    ports:", "      - \"${PORT:-8080}:80\"");
    const upstream = units.filter((u) => u.endpoints.length).map((u) => u.name);
    if (upstream.length) out.push("    depends_on:", ...upstream.map((u) => `      - ${u}`));
    out.push("    restart: unless-stopped");
  }
  out.push("volumes:", "  db-data:");
  return out.join("\n") + "\n";
}

function readme(input: StandaloneExportInput, units: ServiceUnit[], webs: { name: string; mount: string }[], schemas: string[]): string {
  return `# ${input.name} — exportación autónoma

Generado por Forja a partir de \`forja.json\`. Funciona sin Forja: Postgres, un contenedor por servicio y un gateway.

\`\`\`bash
cp .env.example .env    # pon contraseñas propias
docker compose up --build
# http://localhost:8080
\`\`\`

## Qué contiene

| Pieza | Qué hace |
|---|---|
| \`db\` | Postgres 17. Volumen \`db-data\`. |
| \`migrate\` | Crea los roles, ${schemas.length ? `los esquemas (${schemas.join(", ")}) y ` : ""}la cola de tareas, y aplica las migraciones una sola vez (\`public._forja_migrations\`). |
${units.map((u) => `| \`${u.name}\` | ${u.endpoints.length ? `${u.endpoints.length} endpoints${u.component.kind === "api" ? ` en \`/_api/${u.component.route}/…\`` : " en `/_api/…`"}` : "Sin endpoints"}${u.jobs.length ? `, tareas: ${u.jobs.map((j) => `\`${j.name}\``).join(", ")}` : ""}${u.component.database ? `. Base de datos: esquema \`${u.component.database}\`, rol propio` : ""}. |`).join("\n")}
| \`gateway\` | nginx: ${webs.length ? webs.map((w) => `\`${w.name}\` en \`${w.mount}\``).join(", ") : "sin frontends"}; reparte \`/_api\` entre los servicios. |

## Diferencias con Forja

- **No incluidos** (responden 501): inicio de sesión de la app (\`ctx.user\` es \`null\` y \`ctx.requireUser()\` responde 401), archivos, correo, IA, tiempo real y pagos de Forja. Sustitúyelos por servicios propios antes de usar esas funciones.
- **Tareas**: cola compartida en \`public.forja_jobs\`, al menos una vez, 3 intentos con espera creciente; cada servicio ejecuta solo sus tareas. \`schedule\` funciona con cron. Las tareas fallidas quedan con estado \`dead\`.
- **Caché** (\`ctx.cache\`): en memoria de cada réplica.
- **Secretos**: variables de entorno con el mismo nombre${input.secrets.length ? ` (${input.secrets.map((s) => `\`${s}\``).join(", ")})` : ""}. Forja nunca exporta sus valores.
- **Datos**: la exportación no copia filas; parte de una base vacía. Para traer datos, exporta la base desde Forja (Datos → Exportar) e impórtala.

Vuelve a exportar desde Forja tras cambiar la app; no edites \`services/*/bundles\` a mano.
`;
}

export async function exportStandalone(input: StandaloneExportInput): Promise<ExportTree> {
  const { files } = input;
  const { error } = safeLayout(files);
  if (error) throw new BuildError([{ file: "forja.json", text: error }]);
  const layout = files["forja.json"] ? readLayout(files) : layoutOf(files);
  const problems = await checkProject(files);
  if (problems.length) throw new BuildError(problems);

  const tree: ExportTree = {};
  const put = (p: string, content: string | Uint8Array) => { tree[p] = content; };

  // --- Frontends -> gateway ------------------------------------------------------------------
  const pages = pageRoutes(files, layout);
  const webs = layout.components
    .filter((c) => (c.kind === "app" && pages.some((p) => !p.component)) || c.kind === "web")
    .map((c) => ({ name: c.name, mount: c.mount, root: c.root, staticDir: c.paths.static }));
  for (const web of webs) {
    const { js, css } = await buildClient(files, { minify: true, component: web.name });
    put(`gateway/html/_forja/${web.name}.js`, js);
    put(`gateway/html/_forja/${web.name}.css`, css);
    const dir = web.mount === "/" ? "" : `${web.mount.slice(1)}/`;
    const title = escapeHtml(input.name);
    put(`gateway/html/${dir}index.html`, `<!doctype html><html lang="es"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title><link rel="stylesheet" href="/_forja/${web.name}.css"><script>window.__FORJA__=${JSON.stringify({ base: "", projectId: input.slug, env: "published" })}</script></head>
<body><div id="root"></div><script type="module" src="/_forja/${web.name}.js"></script></body></html>
`);
    for (const [file, content] of Object.entries(files)) {
      const local = web.root ? (file.startsWith(web.root) ? file.slice(web.root.length) : null) : file;
      // Served at <mount>/static/… whatever the folder is called (forja.json paths.static).
      const rel = local === null ? null : under(local, web.staticDir);
      if (rel === null || rel.startsWith("__dev/")) continue;
      put(`gateway/html/${dir}static/${rel}`, staticBytes(content));
    }
  }

  // --- Services ------------------------------------------------------------------------------
  const units = services(files, layout);
  const allJobs = jobFiles(files, layout).map((j) => j.name);
  const projectDeps = readDeps(files);
  const runtime = readFileSync(path.join(STANDALONE_DIR, "server.mjs"), "utf8");
  for (const unit of units) {
    const base = `services/${unit.name}`;
    const imports = new Set<string>();
    const compile = async (file: string) => {
      const compiled = await compileServerModule(files, file);
      const code = readFileSync(compiled.file, "utf8");
      for (const name of bareImports(code)) imports.add(name);
      put(`${base}/bundles/${bundleName(file)}`, code);
      return bundleName(file);
    };
    const endpoints = [];
    for (const e of unit.endpoints) endpoints.push({ method: e.method, route: e.route, file: e.file, bundle: await compile(e.file) });
    const jobs = [];
    for (const j of unit.jobs) {
      const settings = readJobSettings(files[j.file]!);
      jobs.push({ name: j.name, file: j.file, bundle: await compile(j.file), schedule: settings.schedule, timezone: settings.timezone });
    }
    put(`${base}/manifest.json`, JSON.stringify({
      component: unit.name, schema: unit.component.database ?? null, endpoints, jobs, allJobs, secrets: input.secrets,
      maxConcurrency: unit.component.maxConcurrency ?? (unit.component.kind === "worker" ? 1 : 8),
    }, null, 2) + "\n");
    const dependencies: Record<string, string> = {};
    for (const name of RUNTIME_PACKAGES) dependencies[name] = installedVersion(name);
    for (const name of [...imports].sort()) dependencies[name] = projectDeps[name] ?? installedVersion(name);
    put(`${base}/package.json`, JSON.stringify({ name: `${input.slug}-${unit.name}`, private: true, type: "module", dependencies }, null, 2) + "\n");
    put(`${base}/server.mjs`, runtime);
    put(`${base}/Dockerfile`, `FROM node:22-alpine
WORKDIR /app
COPY package.json ./
RUN npm install --omit=dev --ignore-scripts --no-audit --no-fund
COPY . .
ENV NODE_ENV=production PORT=3000
EXPOSE 3000
USER node
CMD ["node", "server.mjs"]
`);
  }

  // --- Database ------------------------------------------------------------------------------
  const schemas = layout.components.flatMap((c) => (c.database ? [c.database] : []));
  const migrations = layoutMigrations(files, layout)
    .map((m) => ({ path: m.path, schema: m.schema }))
    .sort((a, b) => (a.schema ?? "").localeCompare(b.schema ?? "") || Number(BigInt(/(\d+)_[^/]*$/.exec(a.path)![1]!) - BigInt(/(\d+)_[^/]*$/.exec(b.path)![1]!)));
  for (const m of migrations) put(`migrate/migrations/${m.path}`, files[m.path]!);
  put("migrate/plan.json", JSON.stringify({
    appRole: { role: "forja_app", passwordEnv: "APP_DB_PASSWORD" },
    schemas: schemas.map((schema) => ({ schema, role: dataRole(schema), passwordEnv: envName(schema) })),
    migrations,
  }, null, 2) + "\n");
  put("migrate/migrate.mjs", readFileSync(path.join(STANDALONE_DIR, "migrate.mjs"), "utf8"));
  put("migrate/package.json", JSON.stringify({ name: `${input.slug}-migrate`, private: true, type: "module", dependencies: { pg: installedVersion("pg") } }, null, 2) + "\n");
  put("migrate/Dockerfile", `FROM node:22-alpine
WORKDIR /app
COPY package.json ./
RUN npm install --omit=dev --ignore-scripts --no-audit --no-fund
COPY . .
USER node
CMD ["node", "migrate.mjs"]
`);

  // --- Gateway, compose, docs ----------------------------------------------------------------
  put("gateway/nginx.conf", nginxConf(units, webs.map((w) => w.mount)));
  put("gateway/Dockerfile", `FROM nginx:1.27-alpine
COPY nginx.conf /etc/nginx/conf.d/default.conf
COPY html /usr/share/nginx/html
`);
  if (!webs.length) put("gateway/html/.keep", "");
  put("docker-compose.yml", compose(input.slug, units, schemas, input.secrets, webs.length > 0));
  put(".env.example", [
    "# Passwords for the database and each role. Use long random values.",
    "POSTGRES_PASSWORD=change-me",
    "APP_DB_PASSWORD=change-me",
    ...schemas.map((s) => `${envName(s)}=change-me`),
    "PORT=8080",
    ...(input.secrets.length ? ["", "# The project's secrets (Forja never exports their values)."] : []),
    ...input.secrets.map((s) => `${s}=`),
  ].join("\n") + "\n");
  put("README.md", readme(input, units, webs, schemas));
  put(".dockerignore", "node_modules\n");
  return Object.fromEntries(Object.entries(tree).map(([p, v]) => [`${input.slug}/${p}`, v]));
}
